// Command caniemailgen snapshots caniemail.com's support data for the clients
// the sanitize package simulates into caniemail_gen.go.
package main

import (
	"bytes"
	"encoding/json"
	"fmt"
	"go/format"
	"io"
	"log"
	"net/http"
	"os"
	"sort"
	"strings"
)

const source = "https://www.caniemail.com/api/data.json"

// Keys are the sanitize.Client IDs; values pick the caniemail column that represents them.
var targets = map[string][2]string{
	"gmail":           {"gmail", "desktop-webmail"},
	"apple-mail":      {"apple-mail", "macos"},
	"outlook-windows": {"outlook", "windows"},
	"outlook-com":     {"outlook", "outlook-com"},
	"yahoo":           {"yahoo", "desktop-webmail"},
	"samsung-email":   {"samsung-email", "android"},
	"thunderbird":     {"thunderbird", "macos"},
}

type feature struct {
	Slug  string                                `json:"slug"`
	Stats map[string]map[string]json.RawMessage `json:"stats"`
}

func main() {
	resp, err := http.Get(source)
	if err != nil {
		log.Fatal(err)
	}
	defer resp.Body.Close()
	raw, err := io.ReadAll(resp.Body)
	if err != nil {
		log.Fatal(err)
	}

	var data struct {
		LastUpdate string    `json:"last_update_date"`
		Data       []feature `json:"data"`
	}
	if err := json.Unmarshal(raw, &data); err != nil {
		log.Fatal(err)
	}

	clients := make([]string, 0, len(targets))
	for id := range targets {
		clients = append(clients, id)
	}
	sort.Strings(clients)

	var out bytes.Buffer
	fmt.Fprintf(&out, "// Code generated by go/sanitize/internal/caniemailgen; DO NOT EDIT.\n\n")
	fmt.Fprintf(&out, "// Source: %s (last updated %s)\n", source, data.LastUpdate)
	fmt.Fprintf(&out, "// caniemail data: Copyright (c) 2019 Rémi Parmentier, MIT License.\n\n")
	fmt.Fprintf(&out, "package sanitize\n\n")
	fmt.Fprintf(&out, "var caniemailFeatures = map[string]bool{\n")
	for _, f := range data.Data {
		fmt.Fprintf(&out, "%q: true,\n", f.Slug)
	}
	fmt.Fprintf(&out, "}\n\n")
	fmt.Fprintf(&out, "var caniemail = map[string]map[string]support{\n")
	for _, id := range clients {
		target := targets[id]
		fmt.Fprintf(&out, "%q: {\n", id)
		for _, f := range data.Data {
			versions, ok := f.Stats[target[0]][target[1]]
			if !ok {
				continue
			}
			level, err := latest(versions)
			if err != nil {
				log.Fatalf("%s %s: %v", f.Slug, id, err)
			}
			switch level {
			case "n":
				fmt.Fprintf(&out, "%q: unsupported,\n", f.Slug)
			case "a":
				fmt.Fprintf(&out, "%q: partial,\n", f.Slug)
			}
		}
		fmt.Fprintf(&out, "},\n")
	}
	fmt.Fprintf(&out, "}\n")

	src, err := format.Source(out.Bytes())
	if err != nil {
		log.Fatal(err)
	}
	if err := os.WriteFile("caniemail_gen.go", src, 0o644); err != nil {
		log.Fatal(err)
	}
}

// latest returns the support letter of the last version in the object. Version
// keys mix dates and version numbers, so only caniemail's own (chronological)
// order identifies the newest one; a Go map would lose it.
func latest(versions json.RawMessage) (string, error) {
	dec := json.NewDecoder(bytes.NewReader(versions))
	if _, err := dec.Token(); err != nil {
		return "", err
	}
	var value string
	for dec.More() {
		if _, err := dec.Token(); err != nil {
			return "", err
		}
		if err := dec.Decode(&value); err != nil {
			return "", err
		}
	}
	level, _, _ := strings.Cut(strings.TrimSpace(value), " ")
	return level, nil
}
